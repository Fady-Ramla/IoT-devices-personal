# ============================================================
# TrustFlow - Zero Trust Decision
#
# Responsibility:
# - Validate Trust Score
# - Validate Trust State / Action combinations
# - Validate final Security Decision
# - Validate explicit device block/unblock and reroute decisions
#
# This module does NOT:
# - Calculate Trust Score
# - Calculate Trust State
# - Run ML
# - Calculate the normal Security Action
# - Capture packets
# - Install OpenFlow rules
# ============================================================


from zero_trust.zero_trust_policy import (
    MIN_SCORE,
    MAX_SCORE,

    TRUSTED,
    UNTRUSTED,
    ACTION_ALLOW,
    ACTION_KEEP_UNTRUSTED,
    ACTION_BLOCK_DEVICE,
    ACTION_UNBLOCK_DEVICE,
    ACTION_REROUTE,

    SEVERITY_LOW,
    SEVERITY_MEDIUM,
    SEVERITY_HIGH,
    SEVERITY_CRITICAL,

    PREDICTION_BENIGN,
    PREDICTION_MALICIOUS,

    VALID_ACTIONS,
    VALID_PREDICTIONS,
)


class ZeroTrustDecision:
    """
    Zero Trust decision validation layer.

    The normal security decision is generated by
    ZeroTrustEngine.

    This class validates that decision and provides
    explicit device enforcement actions are validated independently
    from Trust Score evaluation.
    """

    # ========================================================
    # Validate Trust Score
    # ========================================================

    @staticmethod
    def validate_score(score):

        if isinstance(score, bool):
            raise ValueError(
                "Trust Score cannot be boolean."
            )

        if not isinstance(score, (int, float)):
            raise ValueError(
                "Trust Score must be numeric."
            )

        if score < MIN_SCORE or score > MAX_SCORE:
            raise ValueError(
                "Trust Score must be between 0 and 100."
            )

        return score

    # ========================================================
    # Validate Prediction
    # ========================================================

    @staticmethod
    def validate_prediction(prediction):

        if prediction is None:
            return None

        if prediction not in VALID_PREDICTIONS:
            raise ValueError(
                "Invalid prediction: {}".format(
                    prediction
                )
            )

        return prediction

    # ========================================================
    # Validate Trust State
    # ========================================================

    @staticmethod
    def validate_trust_state(trust_state):

        if trust_state not in (
            TRUSTED,
            UNTRUSTED,
        ):
            raise ValueError(
                "Unknown Trust State: {}".format(
                    trust_state
                )
            )

        return True

    # ========================================================
    # Validate Action
    # ========================================================

    @staticmethod
    def validate_action(action):

        if action not in VALID_ACTIONS:
            raise ValueError(
                "Invalid Security Action: {}".format(
                    action
                )
            )

        return True

    # ========================================================
    # Validate Decision
    # ========================================================

    @staticmethod
    def validate_decision(
        trust_score,
        trust_state,
        action,
    ):
        """Validate a normal action against trust state.

        BLOCK_DEVICE and UNBLOCK_DEVICE are explicit Security
        commands; they are not inferred from score or trust state.
        REROUTE is also an explicit network action.
        """
        ZeroTrustDecision.validate_score(trust_score)
        ZeroTrustDecision.validate_trust_state(trust_state)
        ZeroTrustDecision.validate_action(action)

        if action == ACTION_REROUTE:
            return True

        expected = (
            ACTION_ALLOW
            if trust_state == TRUSTED
            else ACTION_KEEP_UNTRUSTED
        )
        if action != expected:
            raise ValueError(
                "Invalid action for {} state: {}".format(
                    trust_state, action
                )
            )

        return True

    # ========================================================
    # Validate explicit device enforcement action
    # ========================================================

    @staticmethod
    def validate_device_action(action, mac, ip=None):
        """Validate a Security-issued block/unblock command.

        MAC is the enforcement identity. IP is optional metadata and
        is deliberately not used to match the OpenFlow drop rule.
        """
        import ipaddress
        import re

        if not isinstance(action, str):
            raise ValueError("action must be a string")
        action = action.strip().upper()
        if action not in (ACTION_BLOCK_DEVICE, ACTION_UNBLOCK_DEVICE):
            raise ValueError("action must be BLOCK_DEVICE or UNBLOCK_DEVICE")

        if not isinstance(mac, str):
            raise ValueError("mac is required and must be a string")
        mac = mac.strip().lower()
        if not re.fullmatch(r"(?:[0-9a-f]{2}:){5}[0-9a-f]{2}", mac):
            raise ValueError("mac must be a colon-separated 6-byte address")

        if ip is not None:
            if not isinstance(ip, str) or not ip.strip():
                raise ValueError("ip must be a non-empty IP address when provided")
            try:
                ip = str(ipaddress.ip_address(ip.strip()))
            except ValueError:
                raise ValueError("ip must be a valid IPv4 or IPv6 address")

        return {"action": action, "mac": mac, "ip": ip}

    # ========================================================
    # Validate Final Decision Object
    # ========================================================

    @staticmethod
    def validate_final_decision(decision):
        """
        Validate a complete decision returned by
        ZeroTrustEngine.
        """

        if not isinstance(decision, dict):
            raise ValueError(
                "Decision must be a dictionary."
            )

        required_fields = (
            "device",
            "trust_score",
            "trust_state",
            "action",
            "severity",
        )

        for field in required_fields:

            if field not in decision:
                raise ValueError(
                    "Missing decision field: {}".format(
                        field
                    )
                )

        ZeroTrustDecision.validate_score(
            decision["trust_score"]
        )

        ZeroTrustDecision.validate_trust_state(
            decision["trust_state"]
        )

        ZeroTrustDecision.validate_action(
            decision["action"]
        )

        ZeroTrustDecision.validate_decision(
            trust_score=decision["trust_score"],
            trust_state=decision["trust_state"],
            action=decision["action"],
        )

        if decision["severity"] not in (
            SEVERITY_LOW,
            SEVERITY_MEDIUM,
            SEVERITY_HIGH,
            SEVERITY_CRITICAL,
        ):
            raise ValueError(
                "Invalid severity: {}".format(
                    decision["severity"]
                )
            )

        return True

    # ========================================================
    # REROUTE Decision
    # ========================================================

    def reroute(
        self,
        device,
        trust_score,
        trust_state,
        reason="Traffic rerouting requested.",
    ):
        """
        Generate an explicit REROUTE decision.

        REROUTE is a special Network action.
        It does not change the Trust Score or Trust State.
        """

        trust_score = self.validate_score(
            trust_score
        )

        self.validate_trust_state(
            trust_state
        )

        decision = {
            "device": device,
            "trust_score": trust_score,
            "trust_state": trust_state,
            "action": ACTION_REROUTE,
            "severity": SEVERITY_MEDIUM,
            "event": None,
            "attack_type": None,
            "prediction": None,
            "reason": reason,
        }

        self.validate_final_decision(
            decision
        )

        return decision


# ============================================================
# Main Test
# ============================================================

def main():
    validator = ZeroTrustDecision()
    print("TRUSTED/ALLOW:", validator.validate_decision(90, TRUSTED, ACTION_ALLOW))
    print("UNTRUSTED/KEEP_UNTRUSTED:",
          validator.validate_decision(20, UNTRUSTED, ACTION_KEEP_UNTRUSTED))
    print("Explicit block:", validator.validate_device_action(
        ACTION_BLOCK_DEVICE, "02:00:00:00:00:01", "10.0.0.1"))
    print("Explicit unblock:", validator.validate_device_action(
        ACTION_UNBLOCK_DEVICE, "02:00:00:00:00:01", "10.0.0.1"))


if __name__ == "__main__":
    main()
