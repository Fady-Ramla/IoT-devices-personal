# zero_trust_decision.py
# ============================================================
# TrustFlow - Zero Trust Decision
#
# Responsibility:
# - Validate Trust Score
# - Validate Trust State / Action combinations
# - Validate final Security Decision
# - Generate special RESTORE / REROUTE decisions
#
# This module does NOT:
# - Calculate Trust Score
# - Calculate Trust State
# - Run ML
# - Calculate the normal Security Action
# - Capture packets
# - Install OpenFlow rules
# ============================================================


from zero_trust.zero_trust_policy import (
    MIN_SCORE,
    MAX_SCORE,

    TRUSTED,
    UNTRUSTED,
    QUARANTINED,

    ACTION_ALLOW,
    ACTION_KEEP_UNTRUSTED,
    ACTION_QUARANTINE,
    ACTION_RESTORE,
    ACTION_REROUTE,

    SEVERITY_LOW,
    SEVERITY_MEDIUM,
    SEVERITY_HIGH,
    SEVERITY_CRITICAL,

    PREDICTION_BENIGN,
    PREDICTION_MALICIOUS,

    VALID_ACTIONS,
    VALID_PREDICTIONS,
)


class ZeroTrustDecision:
    """
    Zero Trust decision validation layer.

    The normal security decision is generated by
    ZeroTrustEngine.

    This class validates that decision and provides
    explicit special decisions such as RESTORE and REROUTE.
    """

    # ========================================================
    # Validate Trust Score
    # ========================================================

    @staticmethod
    def validate_score(score):

        if isinstance(score, bool):
            raise ValueError(
                "Trust Score cannot be boolean."
            )

        if not isinstance(score, (int, float)):
            raise ValueError(
                "Trust Score must be numeric."
            )

        if score < MIN_SCORE or score > MAX_SCORE:
            raise ValueError(
                "Trust Score must be between 0 and 100."
            )

        return score

    # ========================================================
    # Validate Prediction
    # ========================================================

    @staticmethod
    def validate_prediction(prediction):

        if prediction is None:
            return None

        if prediction not in VALID_PREDICTIONS:
            raise ValueError(
                "Invalid prediction: {}".format(
                    prediction
                )
            )

        return prediction

    # ========================================================
    # Validate Trust State
    # ========================================================

    @staticmethod
    def validate_trust_state(trust_state):

        if trust_state not in (
            TRUSTED,
            UNTRUSTED,
            QUARANTINED,
        ):
            raise ValueError(
                "Unknown Trust State: {}".format(
                    trust_state
                )
            )

        return True

    # ========================================================
    # Validate Action
    # ========================================================

    @staticmethod
    def validate_action(action):

        if action not in VALID_ACTIONS:
            raise ValueError(
                "Invalid Security Action: {}".format(
                    action
                )
            )

        return True

    # ========================================================
    # Validate Decision
    # ========================================================

    @staticmethod
    def validate_decision(
        trust_score,
        trust_state,
        action,
    ):
        """
        Validate that the selected Security Action is
        compatible with the Trust State.

        Normal actions:

        TRUSTED
            -> ALLOW

        UNTRUSTED
            -> KEEP_UNTRUSTED

        QUARANTINED
            -> QUARANTINE

        Special actions:

            RESTORE
            REROUTE

        are also explicitly supported.
        """

        ZeroTrustDecision.validate_score(
            trust_score
        )

        ZeroTrustDecision.validate_trust_state(
            trust_state
        )

        ZeroTrustDecision.validate_action(
            action
        )

        # ----------------------------------------------------
        # TRUSTED
        # ----------------------------------------------------

        if trust_state == TRUSTED:

            if action not in (
                ACTION_ALLOW,
                ACTION_RESTORE,
                ACTION_REROUTE,
            ):
                raise ValueError(
                    "Invalid action for TRUSTED state: {}".format(
                        action
                    )
                )

        # ----------------------------------------------------
        # UNTRUSTED
        # ----------------------------------------------------

        elif trust_state == UNTRUSTED:

            if action not in (
                ACTION_KEEP_UNTRUSTED,
                ACTION_REROUTE,
            ):
                raise ValueError(
                    "Invalid action for UNTRUSTED state: {}".format(
                        action
                    )
                )

        # ----------------------------------------------------
        # QUARANTINED
        # ----------------------------------------------------

        elif trust_state == QUARANTINED:

            if action not in (
                ACTION_QUARANTINE,
                ACTION_REROUTE,
            ):
                raise ValueError(
                    "Invalid action for QUARANTINED state: {}".format(
                        action
                    )
                )

        return True

    # ========================================================
    # Validate Final Decision Object
    # ========================================================

    @staticmethod
    def validate_final_decision(decision):
        """
        Validate a complete decision returned by
        ZeroTrustEngine.
        """

        if not isinstance(decision, dict):
            raise ValueError(
                "Decision must be a dictionary."
            )

        required_fields = (
            "device",
            "trust_score",
            "trust_state",
            "action",
            "severity",
        )

        for field in required_fields:

            if field not in decision:
                raise ValueError(
                    "Missing decision field: {}".format(
                        field
                    )
                )

        ZeroTrustDecision.validate_score(
            decision["trust_score"]
        )

        ZeroTrustDecision.validate_trust_state(
            decision["trust_state"]
        )

        ZeroTrustDecision.validate_action(
            decision["action"]
        )

        ZeroTrustDecision.validate_decision(
            trust_score=decision["trust_score"],
            trust_state=decision["trust_state"],
            action=decision["action"],
        )

        if decision["severity"] not in (
            SEVERITY_LOW,
            SEVERITY_MEDIUM,
            SEVERITY_HIGH,
            SEVERITY_CRITICAL,
        ):
            raise ValueError(
                "Invalid severity: {}".format(
                    decision["severity"]
                )
            )

        return True

    # ========================================================
    # RESTORE Decision
    # ========================================================

    def restore(
        self,
        device,
        trust_score=80,
        reason="Authorized device restoration.",
    ):
        """
        Generate an explicit RESTORE decision.

        RESTORE is a special action and is not generated
        by the normal Trust State -> Action mapping.
        """

        trust_score = self.validate_score(
            trust_score
        )

        decision = {
            "device": device,
            "trust_score": trust_score,
            "trust_state": TRUSTED,
            "action": ACTION_RESTORE,
            "severity": SEVERITY_LOW,
            "event": "RECOVERY",
            "attack_type": None,
            "prediction": None,
            "reason": reason,
        }

        self.validate_final_decision(
            decision
        )

        return decision

    # ========================================================
    # REROUTE Decision
    # ========================================================

    def reroute(
        self,
        device,
        trust_score,
        trust_state,
        reason="Traffic rerouting requested.",
    ):
        """
        Generate an explicit REROUTE decision.

        REROUTE is a special Network action.
        It does not change the Trust Score or Trust State.
        """

        trust_score = self.validate_score(
            trust_score
        )

        self.validate_trust_state(
            trust_state
        )

        decision = {
            "device": device,
            "trust_score": trust_score,
            "trust_state": trust_state,
            "action": ACTION_REROUTE,
            "severity": SEVERITY_MEDIUM,
            "event": None,
            "attack_type": None,
            "prediction": None,
            "reason": reason,
        }

        self.validate_final_decision(
            decision
        )

        return decision


# ============================================================
# Main Test
# ============================================================

def main():

    print("=" * 70)
    print("TRUSTFLOW ZERO TRUST DECISION")
    print("=" * 70)

    decision_validator = ZeroTrustDecision()

    device = "10.0.0.5"

    # --------------------------------------------------------
    # Validate normal decision
    # --------------------------------------------------------

    print("\n[1] VALIDATE TRUSTED DECISION")

    trusted_decision = {
        "device": device,
        "trust_score": 100,
        "trust_state": TRUSTED,
        "action": ACTION_ALLOW,
        "severity": SEVERITY_LOW,
    }

    print(
        decision_validator.validate_final_decision(
            trusted_decision
        )
    )

    # --------------------------------------------------------
    # Validate untrusted decision
    # --------------------------------------------------------

    print("\n[2] VALIDATE UNTRUSTED DECISION")

    untrusted_decision = {
        "device": device,
        "trust_score": 50,
        "trust_state": UNTRUSTED,
        "action": ACTION_KEEP_UNTRUSTED,
        "severity": SEVERITY_HIGH,
    }

    print(
        decision_validator.validate_final_decision(
            untrusted_decision
        )
    )

    # --------------------------------------------------------
    # Validate quarantined decision
    # --------------------------------------------------------

    print("\n[3] VALIDATE QUARANTINED DECISION")

    quarantine_decision = {
        "device": device,
        "trust_score": 20,
        "trust_state": QUARANTINED,
        "action": ACTION_QUARANTINE,
        "severity": SEVERITY_CRITICAL,
    }

    print(
        decision_validator.validate_final_decision(
            quarantine_decision
        )
    )

    # --------------------------------------------------------
    # RESTORE
    # --------------------------------------------------------

    print("\n[4] RESTORE")

    restore_decision = decision_validator.restore(
        device=device,
        trust_score=80,
    )

    print(restore_decision)

    # --------------------------------------------------------
    # REROUTE
    # --------------------------------------------------------

    print("\n[5] REROUTE")

    reroute_decision = decision_validator.reroute(
        device=device,
        trust_score=65,
        trust_state=UNTRUSTED,
        reason="Network path recovery requested.",
    )

    print(reroute_decision)

    print("\n" + "=" * 70)


if __name__ == "__main__":
    main()
